BEGIN;

-- Stop if product relations already exist in any application schema.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE c.relname IN ('simcard_produk', 'simcard_tier_harga')
      AND c.relkind IN ('r', 'p', 'v', 'm', 'f')
      AND n.nspname NOT IN ('pg_catalog', 'information_schema')
  ) THEN
    RAISE EXCEPTION 'Product tables already exist; inspect their schema before initializing.';
  END IF;
END
$$;

CREATE TABLE public.simcard_produk (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kategori TEXT NOT NULL DEFAULT 'PREPAID'
        CHECK (kategori IN ('IOT_M2M', 'POSTPAID', 'PREPAID', 'SPI', 'PAYU')),
    penyedia TEXT NOT NULL DEFAULT 'DPT',
    status_stok TEXT NOT NULL DEFAULT 'OPEN'
        CHECK (status_stok IN ('OPEN', 'CLOSED')),
    provider TEXT,
    nama_paket TEXT,
    kuota_gb NUMERIC DEFAULT 0,
    cogs NUMERIC DEFAULT 0,
    biaya_simcard NUMERIC,
    cogs_kuota_bulanan NUMERIC,
    harga_tp NUMERIC,
    harga_eup NUMERIC,
    pajak_persen NUMERIC,
    remarks TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.simcard_tier_harga (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produk_id INTEGER NOT NULL
        REFERENCES public.simcard_produk(id) ON DELETE CASCADE,
    tier_ke INTEGER NOT NULL,
    min_unit INTEGER NOT NULL,
    max_unit INTEGER,
    margin_persen NUMERIC NOT NULL,
    UNIQUE (produk_id, tier_ke)
);

CREATE TABLE IF NOT EXISTS public.kalkulator_pengaturan (
    key VARCHAR(50) PRIMARY KEY,
    value JSONB NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
